#!/usr/bin/env bash
# Prints a markdown report of EXPLAIN (ANALYZE, BUFFERS) for the main lexical queries.
# Usage: db/explain.sh > docs/query-plans.md
# Each query is run twice and the second (warm cache) plan is shown.
set -euo pipefail
cd "$(dirname "$0")"
. ./lib.sh

q() { run_sql -At -c "$1"; }

echo "# Query plans"
echo
echo "Generated by \`db/explain.sh\` on $(date -u +%Y-%m-%d)."
echo
echo "- PostgreSQL: $(q 'SHOW server_version')"
echo "- Hardware: $(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown), $(($(sysctl -n hw.memsize 2>/dev/null || echo 0) / 1073741824)) GB RAM, $(uname -sm)"
echo "- Rows: search_term=$(q 'SET search_path TO '"$SCHEMA"',public; SELECT count(*) FROM search_term' | tail -1)," \
     "description=$(q 'SET search_path TO '"$SCHEMA"',public; SELECT count(*) FROM description' | tail -1)," \
     "relationship=$(q 'SET search_path TO '"$SCHEMA"',public; SELECT count(*) FROM relationship' | tail -1)"
echo "- Cache: warm (each statement executed once before the plan shown)"
echo

plan() { # title, sql
  echo "## $1"
  echo
  echo '```sql'
  echo "$2"
  echo '```'
  echo
  echo '```'
  run_sql -At <<SQL | sed '/^SET$/d;/^set_config/d'
SET search_path TO $SCHEMA, public;
SET pg_trgm.word_similarity_threshold = 0.5;
\o /dev/null
$2;
$2;
\o
EXPLAIN (ANALYZE, BUFFERS) $2
SQL
  echo '```'
  echo
}

# The first statement of the heredoc executes the query once to warm the cache.
plan "Word search, one word (tag filter)" "SELECT count(DISTINCT concept_id) FROM search_term WHERE tsv @@ to_tsquery('simple', 'pain:*') AND semantic_tag = ANY(ARRAY['finding'])"

plan "Word search, two words, ranked page" "WITH matched AS (
  SELECT concept_id, term, preferred_term, semantic_tag, children_count, term_length,
         CASE WHEN term_lower = 'chest pain' THEN 0 WHEN term_lower LIKE 'chest pain%' THEN 1 ELSE 2 END AS match_rank
  FROM search_term WHERE tsv @@ to_tsquery('simple', 'chest:* & pain:*') AND semantic_tag = ANY(ARRAY['finding'])
), best AS (SELECT DISTINCT ON (concept_id) * FROM matched ORDER BY concept_id, match_rank, term_length, term)
SELECT concept_id, preferred_term FROM best ORDER BY match_rank, term_length, term, concept_id LIMIT 10 OFFSET 0"

plan "Typo fallback (trigram word similarity)" "SELECT concept_id, word_similarity('chest pian', term) AS sim FROM search_term WHERE 'chest pian' <% term AND semantic_tag = ANY(ARRAY['finding']) ORDER BY sim DESC LIMIT 10"

plan "Exact and prefix lookup (btree on term_lower)" "SELECT concept_id, term FROM search_term WHERE term_lower LIKE 'headache%' ORDER BY term_length LIMIT 10"

plan "Children of a concept (partial index on relationship)" "SELECT r.source_id FROM relationship r WHERE r.destination_id = (SELECT concept_id FROM search_term WHERE term_lower = 'headache' LIMIT 1) AND r.type_id = 116680003 AND r.active"

# Closure table (Phase 5). 56265001 is Heart disease in the International release; change it for other editions.
plan "Descendants page (closure primary key, keyset)" "SELECT a.descendant_id, a.min_depth FROM concept_ancestor a WHERE a.ancestor_id = 56265001 AND a.descendant_id > 0 ORDER BY a.descendant_id LIMIT 101"

plan "Descendant count" "SELECT count(*) FROM concept_ancestor a WHERE a.ancestor_id = 56265001"

plan "Ancestors of a concept (reverse index)" "SELECT a.ancestor_id, a.min_depth FROM concept_ancestor a WHERE a.descendant_id = 22298006 ORDER BY a.min_depth"

plan "Word search restricted to a subtree" "SELECT count(DISTINCT concept_id) FROM search_term WHERE tsv @@ to_tsquery('simple', 'failure:*') AND (search_term.concept_id = 56265001 OR EXISTS (SELECT 1 FROM concept_ancestor ca WHERE ca.ancestor_id = 56265001 AND ca.descendant_id = search_term.concept_id))"

cat <<'NOTES'
## Notes

- The typo fallback first ran against `term_lower`, which has no trigram index, so the planner
  used the semantic-tag index and filtered 58,578 rows. A single run took about 170 to 215 ms.
  After querying `term` (which carries the trigram GIN index) it took about 7 ms in a single run.
  These are single runs on one machine, not a benchmark. See `docs/benchmarks.md` once it exists.
- Word search matches the start of words, so "ache" does not match "headache". This differs from the
  earlier substring (`ILIKE %word%`) behaviour and is a deliberate trade for index use.
- Planner choices depend on table statistics. Run `ANALYZE` after loading (the loader does).
- Closure table on this data set: 7,611,410 ancestor pairs, maximum depth 22, built breadth first by
  `db/sql/201_closure.sql` in 2 min 01 s (single run), 837 MB including both indexes.
NOTES
